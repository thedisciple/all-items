export type Locale = "ru" | "en";
export type MessageKey = keyof typeof ru;
const messages: Record<Locale, Record<MessageKey, string>> = { ru, en };

export function translate(locale: Locale, key: MessageKey, values: Record<string, string | number> = {}) {
  const number = new Intl.NumberFormat(locale);
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, typeof value === "number" ? number.format(value) : value), messages[locale][key]);
}

export function formatItemCount(locale: Locale, count: number) {
  if (locale === "en") return `${new Intl.NumberFormat(locale).format(count)} ${count === 1 ? "item" : "items"}`;
  const category = new Intl.PluralRules("ru-RU").select(count);
  const noun = category === "one" ? "вещь" : category === "few" ? "вещи" : "вещей";
  return `${new Intl.NumberFormat("ru-RU").format(count)} ${noun}`;
}

export function formatCollectionCount(locale: Locale, count: number) {
  if (locale === "en") return `${new Intl.NumberFormat(locale).format(count)} ${count === 1 ? "collection" : "collections"}`;
  const category = new Intl.PluralRules("ru-RU").select(count);
  const noun = category === "one" ? "коллекция" : category === "few" ? "коллекции" : "коллекций";
  return `${new Intl.NumberFormat("ru-RU").format(count)} ${noun}`;
}

export function formatDate(locale: Locale, value: string) {
  const date = new Date(value);
  return Number.isNaN(date.valueOf()) ? value : new Intl.DateTimeFormat(locale, { dateStyle: "medium" }).format(date);
}
