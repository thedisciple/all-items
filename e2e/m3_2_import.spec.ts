import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";
import sharp from "sharp";
import {createHash} from "node:crypto";
import type {PortableInventory} from "../src/export/import";
import { readInventoryArchive, verifyInventoryArchive } from "../src/export/archive";
import { previewInventoryArchive } from "../src/export/import";

test("downloads a complete archive and imports it twice as new inventories while preserving a populated target", async ({ page }) => {
  test.setTimeout(240_000);
  const image = await sharp({ create: { width: 260, height: 180, channels: 3, background: "#678853" } }).png().toBuffer();


  await page.goto("/inventories/00000000-0000-4000-8000-000000000001");
  await page.locator(".add-dialog-trigger").click();
  const add = page.getByRole("dialog", { name: "Добавить вещь" });
  await add.getByRole("button", { name: "Добавить фото" }).click();
  await add.locator('input[name="photo"]').setInputFiles(await Promise.all([image, ...await Promise.all(["#89784f","#4f7389"].map(background=>sharp({create:{width:300,height:220,channels:3,background}}).png().toBuffer()))].map(async(buffer,index)=>({name:`synthetic-${index}.png`,mimeType:"image/png",buffer}))));
  await expect(add.locator(".gallery-thumbnail")).toHaveCount(3);
  await add.getByLabel("Название").fill("Restored gadget 中文");
  await add.locator(".category-trigger").click();
  await add.locator(".category-options input").nth(0).check();
  await add.locator(".category-options input").nth(2).check();
  await add.getByRole("button", { name: "Сохранить вещь" }).click();
  await expect(page).toHaveURL(/added=/);
  await page.getByRole("link",{name:"Restored gadget 中文",exact:true}).click();
  await expect(page.locator(".gallery-thumbnail")).toHaveCount(3);
  await page.getByRole("button",{name:"Фото 2",exact:true}).click();
  await page.locator(".gallery-primary-button").nth(1).click();
  await expect(page.getByRole("button",{name:"Фото 2 — Основное фото",exact:true})).toBeVisible();
  await page.locator('.gallery-thumbnail[aria-current="true"]').focus();
  await page.keyboard.press("Space");await page.keyboard.press("ArrowLeft");await page.keyboard.press("Space");
  await expect(page.getByRole("button",{name:"Фото 1 — Основное фото",exact:true})).toBeVisible();

  await page.goto("/inventories/00000000-0000-4000-8000-000000000001/collections");
  await page.locator(".collection-create-trigger").click();
  const create = page.getByRole("dialog", { name: "Создать коллекцию" });
  await create.getByLabel("Название коллекции").fill("Portable DIY");
  await create.getByRole("button", { name: "Создать коллекцию" }).click();
  await expect(page).toHaveURL(/\/collections\/[0-9a-f-]+$/);
  await page.getByRole("button", { name: "Добавить вещи" }).click();
  const membership = page.getByRole("dialog", { name: "Добавить вещи" });
  await membership.locator(".collection-item-option").filter({ hasText: "Restored gadget 中文" }).getByRole("checkbox").check();
  await membership.getByRole("button", { name: /Добавить вещи/ }).click();
  await expect(page.locator(".item-row").filter({ hasText: "Restored gadget 中文" })).toBeVisible();
  await page.getByRole("button", { name: /(?:Изменить|Добавить) обложку/ }).click();
  const coverDialog = page.getByRole("dialog", { name: "Обложка коллекции" });
  await coverDialog.getByLabel("Обложка коллекции").selectOption("item_photo");
  await coverDialog.locator('select[name="selectedPhoto"]').selectOption({index:2});
  await expect(coverDialog.getByRole("img", { name: "Предпросмотр обложки" })).toBeVisible();
  await coverDialog.getByRole("button", { name: "Сохранить обложку" }).click();
  await expect(page.locator(".collection-detail-cover")).toBeVisible();

  await page.goto("/inventories/00000000-0000-4000-8000-000000000001/data");
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Скачать архив" }).click();
  const download = await downloadPromise;
  const archivePath = await download.path();
  if (!archivePath) throw new Error("The test archive was not downloaded.");
  const archive = new Uint8Array(await readFile(archivePath));
  expect(verifyInventoryArchive(archive).version).toBe(6);
  expect((await previewInventoryArchive(archive)).items).toBe(1);
  expect((await previewInventoryArchive(archive)).photos).toBe(3);

  const originalContents=readInventoryArchive(archive),originalItem=(originalContents.inventory as PortableInventory).items[0]!;
  async function verifyRestoredGallery(url:string){
    const copy=readInventoryArchive(new Uint8Array(await(await page.request.get(url+"/api/export/archive")).body())),item=(copy.inventory as PortableInventory).items.find(value=>value.inventory_number===originalItem.inventory_number)!;
    expect(item.mediaAssets.map(photo=>({primary:photo.isPrimary,order:photo.displayOrder,crop:photo.cropData}))).toEqual(originalItem.mediaAssets.map(photo=>({primary:photo.isPrimary,order:photo.displayOrder,crop:photo.cropData})));
    expect(item.primaryMediaId).toBe(item.mediaAssets.find(photo=>photo.isPrimary)!.id);
    for(const [index,photo]of item.mediaAssets.entries())for(const variant of ["imagePath","thumbnailPath","sourcePath"] as const){const source=originalItem.mediaAssets[index]![variant],target=photo[variant];expect(Boolean(target)).toBe(Boolean(source));if(source&&target)expect(createHash("sha256").update(copy.files[target]!).digest("hex")).toBe(createHash("sha256").update(originalContents.files[source]!).digest("hex"));}
  }

  const targetOriginal="http://127.0.0.1:3103/inventories/00000000-0000-4000-8000-000000000001";
  await page.goto(targetOriginal);
  await page.locator(".add-dialog-trigger").click();
  const existing=page.getByRole("dialog",{name:"\u0414\u043e\u0431\u0430\u0432\u0438\u0442\u044c \u0432\u0435\u0449\u044c"});
  await existing.getByLabel("\u041d\u0430\u0437\u0432\u0430\u043d\u0438\u0435").fill("Existing target item");
  await existing.getByRole("button",{name:"Сохранить вещь",exact:true}).click();
  await expect(page).toHaveURL(/added=/);
  const beforeTarget=readInventoryArchive(new Uint8Array(await (await page.request.get(`${targetOriginal}/api/export/archive`)).body()));
  async function importCopy(name:string) {
    const request=page.waitForRequest("**/api/import/preview");
    await page.locator('.import-panel input[type="file"]').setInputFiles({name:"portable.zip",mimeType:"application/zip",buffer:Buffer.from(archive)});
    expect((await request).headers()["x-all-items-import"]).toBe("1");
    await expect(page.locator(".import-summary")).toContainText("\u0412\u0435\u0449\u0435\u0439: 1");
    await expect(page.locator(".import-summary")).toContainText("\u041a\u043e\u043b\u043b\u0435\u043a\u0446\u0438\u0439: 1");
    await expect(page.getByLabel("\u041d\u0430\u0437\u0432\u0430\u043d\u0438\u0435 \u043d\u043e\u0432\u043e\u0433\u043e \u0438\u043d\u0432\u0435\u043d\u0442\u0430\u0440\u044f")).toHaveValue("Inventory (2)");
    await page.getByLabel("\u041d\u0430\u0437\u0432\u0430\u043d\u0438\u0435 \u043d\u043e\u0432\u043e\u0433\u043e \u0438\u043d\u0432\u0435\u043d\u0442\u0430\u0440\u044f").fill(name);
    await page.getByRole("button",{name:"\u0418\u043c\u043f\u043e\u0440\u0442\u0438\u0440\u043e\u0432\u0430\u0442\u044c \u043a\u0430\u043a \u043d\u043e\u0432\u044b\u0439 \u0438\u043d\u0432\u0435\u043d\u0442\u0430\u0440\u044c",exact:true}).click();
    await expect(page).toHaveURL(/:3103\/inventories\/[0-9a-f-]{36}$/);
    return page.url();
  }
  await page.goto(`${targetOriginal}/data`);
  const first=await importCopy("Recovered \u4e2d\u6587");
  expect(first).not.toBe(targetOriginal);await verifyRestoredGallery(first);
  await page.getByRole("link",{name:/Restored gadget/}).click();
  expect(new URL(page.url()).pathname.split("/").at(-1)).not.toBe((readInventoryArchive(archive).inventory.items as Array<{id:string}>)[0]!.id);
  await expect(page.locator(".category-selection .category-chip")).toHaveCount(2);
  await expect(page.locator(".gallery-thumbnail")).toHaveCount(3);
  await expect.poll(()=>page.locator(".detail-photo").first().evaluate(image=>(image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
  const firstPhoto=(await page.locator(".detail-photo").first().getAttribute("src"))!;
  await page.goto(`${first}/collections`);
  await page.locator(".collection-card").filter({hasText:"Portable DIY"}).click();
  await expect(page.locator(".item-row").filter({hasText:/Restored gadget/})).toBeVisible();
  await expect.poll(()=>page.locator(".collection-detail-cover").evaluate(image=>(image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
  const firstCover=(await page.locator(".collection-detail-cover").getAttribute("src"))!;
  await page.goto(first);await page.locator(".add-dialog-trigger").click();
  const next=page.getByRole("dialog",{name:"\u0414\u043e\u0431\u0430\u0432\u0438\u0442\u044c \u0432\u0435\u0449\u044c"});
  await next.getByLabel("\u041d\u0430\u0437\u0432\u0430\u043d\u0438\u0435").fill("After restore");
  await next.getByRole("button",{name:"Сохранить вещь",exact:true}).click();
  await expect(page.getByRole("link",{name:/After restore/})).toContainText("INV-000002");
  await page.goto(`${first}/data`);
  const second=await importCopy("Recovered second");expect(second).not.toBe(first);await verifyRestoredGallery(second);
  await expect(page.getByRole("link",{name:/After restore/})).toHaveCount(0);
  await expect(page.getByRole("link",{name:/Restored gadget/})).toContainText("INV-000001");
  const secondPath=new URL(second).pathname,firstPath=new URL(first).pathname;
  expect((await page.request.get(new URL(firstPhoto.replace(firstPath,secondPath),second).href)).status()).toBe(404);
  expect((await page.request.get(new URL(firstCover.replace(firstPath,secondPath),second).href)).status()).toBe(404);
  const afterTarget=readInventoryArchive(new Uint8Array(await (await page.request.get(`${targetOriginal}/api/export/archive`)).body()));
  expect(afterTarget.inventory).toEqual(beforeTarget.inventory);
  const afterSource=readInventoryArchive(new Uint8Array(await (await page.request.get("http://127.0.0.1:3102/inventories/00000000-0000-4000-8000-000000000001/api/export/archive")).body()));
  expect(afterSource.inventory).toEqual(readInventoryArchive(archive).inventory);
  await page.goto(second);
  await page.getByRole("link",{name:/Restored gadget/}).click();
  await expect(page.locator(".gallery-thumbnail")).toHaveCount(3);
  await page.getByRole("button",{name:"Удалить фотографию",exact:true}).click();
  await page.getByRole("alertdialog").getByRole("button",{name:"Удалить фотографию",exact:true}).click();
  await expect(page.locator(".gallery-thumbnail")).toHaveCount(2);
  await page.locator('.gallery-thumbnail[aria-current="true"]').focus();
  await page.keyboard.press("Space");await page.keyboard.press("ArrowRight");await page.keyboard.press("Space");
  await expect(page.getByRole("button",{name:"Фото 2 — Основное фото",exact:true})).toBeVisible();
  await page.goto(`${second}/collections`);
  await page.locator(".collection-card").filter({hasText:"Portable DIY"}).click();
  await expect.poll(()=>page.locator(".collection-detail-cover").evaluate(image=>(image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
  await page.goto(`${second}/data`);
  await page.locator('.import-panel input[type="file"]').setInputFiles({name:"invalid.zip",mimeType:"application/zip",buffer:Buffer.from("invalid")});
  await expect(page.locator(".import-panel [role=alert]")).toContainText("\u0410\u0440\u0445\u0438\u0432");
  await page.locator(".language-switcher").click();await page.getByRole("menuitemradio",{name:"English"}).click();
  await expect(page.locator(".import-panel [role=alert]")).toContainText("The archive");
});
