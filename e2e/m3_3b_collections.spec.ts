import { expect,test,type Page } from "@playwright/test";
import sharp from "sharp";

test.use({ actionTimeout: 10_000 });

async function addPhotoItem(page:Page,name:string,color:string) {
  await page.goto("/inventories/00000000-0000-4000-8000-000000000001");
  await page.locator(".add-dialog-trigger").click();
  const dialog=page.getByRole("dialog",{name:"Добавить вещь"});
  await dialog.getByLabel("Название").fill(name);
  await dialog.locator(".category-trigger").click();
  await dialog.locator('.category-options input[type="checkbox"]').nth(0).check();
  await dialog.locator('.category-options input[type="checkbox"]').nth(2).check();
  await dialog.locator(".category-trigger").click();
  await dialog.getByRole("button",{name:"Добавить фото",exact:true}).click();
  await dialog.locator('input[name="photo"]').setInputFiles({name:"synthetic.png",mimeType:"image/png",buffer:await sharp({create:{width:240,height:400,channels:3,background:color}}).png().toBuffer()});
  const crop=page.getByRole("dialog",{name:"Редактировать фото"});await expect(crop.getByRole("button",{name:"Готово"})).toBeEnabled();
  await crop.getByRole("button",{name:"Готово"}).click();
  await dialog.getByRole("button",{name:"Добавить вещь",exact:true}).click();await expect(page).toHaveURL(/added=/);
}

